package behavior

import (
	"bytes"
	"strings"
	"testing"
	"time"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

// references/completion.md: DisableAutoGenTag drops the generated footer, and
// a man header with a fixed Date and Source makes man output reproducible.
func TestReproducibleDocs(t *testing.T) {
	root := &cobra.Command{Use: "app", Short: "An app", RunE: noop}
	var md bytes.Buffer
	if err := doc.GenMarkdown(root, &md); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(md.String(), "Auto generated by spf13/cobra") {
		t.Fatal("expected the default footer")
	}
	root.DisableAutoGenTag = true
	md.Reset()
	if err := doc.GenMarkdown(root, &md); err != nil {
		t.Fatal(err)
	}
	if strings.Contains(md.String(), "Auto generated") {
		t.Fatalf("footer still present:\n%s", md.String())
	}

	date := time.Date(2026, 1, 2, 0, 0, 0, 0, time.UTC)
	gen := func() string {
		var man bytes.Buffer
		header := &doc.GenManHeader{Title: "APP", Section: "1", Date: &date, Source: "app 1.0"}
		if err := doc.GenMan(root, header, &man); err != nil {
			t.Fatal(err)
		}
		return man.String()
	}
	first := gen()
	if first != gen() || strings.Contains(first, "Auto generated") {
		t.Fatalf("man output not reproducible:\n%s", first)
	}
}
